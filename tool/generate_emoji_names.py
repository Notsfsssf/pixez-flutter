"""Regenerate the filename emoji names from the Unicode English short names."""

import re
import unicodedata
import urllib.request
from pathlib import Path

VERSION = "18.0.0"
SOURCE = f"https://www.unicode.org/Public/{VERSION}/emoji/emoji-test.txt"
ROOT = Path(__file__).resolve().parents[1]


def main():
    data = urllib.request.urlopen(SOURCE).read().decode("utf-8")
    names = {}
    for line in data.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        points, _, comment = line.partition("#")
        codes = [int(code, 16) for code in points.split(";")[0].split()]
        # Presentation selectors do not change an emoji's English name.
        key = "".join(f"\\u{{{code:X}}}" for code in codes if code not in (0xFE0E, 0xFE0F))
        name = re.split(r"\sE[\d.]+\s", comment, maxsplit=1)[1].strip()
        name = name.replace("#", "hash").replace("*", "asterisk").replace("&", "and")
        name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
        names[key] = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")

    output = [
        "// Generated by tool/generate_emoji_names.py. Do not edit by hand.",
        f"// Unicode {VERSION} English short names: {SOURCE}",
        "// Copyright Unicode, Inc. See third_party/unicode/LICENSE.",
        "// SPDX-License-Identifier: Unicode-3.0",
        "const filenameEmojiEnglishNames = <String, String>{",
    ]
    output.extend(f"  '{key}': '{name}'," for key, name in names.items())
    output.append("};\n")
    (ROOT / "lib/utils/emoji_names.dart").write_text("\n".join(output), encoding="utf-8")
    print(f"Generated {len(names)} emoji names from Unicode {VERSION}")


if __name__ == "__main__":
    main()
